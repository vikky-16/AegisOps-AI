def parse_severity(level_str: Optional[str]) -> TelemetrySeverity:
    """Maps raw LogHub log level string to AegisOps TelemetrySeverity enum."""
    if not level_str:
        return TelemetrySeverity.INFO
    lvl = level_str.strip().upper()
    if lvl in ["FATAL", "CRITICAL", "FAILURE", "EMERG"]:
        return TelemetrySeverity.CRITICAL
    if lvl in ["ERROR", "ERR", "SEVERE", "FAILED"]:
        return TelemetrySeverity.ERROR
    if lvl in ["WARN", "WARNING", "NOTICE"]:
        return TelemetrySeverity.WARNING
    return TelemetrySeverity.INFO


class LogHubDatasetParser:
    def __init__(self, base_path: str = BASE_DATASET_PATH):
        self.base_path = base_path

    def list_available_datasets(self) -> List[LogHubDatasetInfo]:
        """Discovers and describes all available LogHub datasets in datasets/loghub/raw/."""
        results: List[LogHubDatasetInfo] = []
        if not os.path.exists(self.base_path):
            return results

        for ds_id, meta in DATASET_METADATA.items():
            ds_dir = os.path.join(self.base_path, ds_id)
            if not os.path.exists(ds_dir):
                continue

            csv_file = os.path.join(ds_dir, f"{ds_id}_2k.log_structured.csv")
            log_file = os.path.join(ds_dir, f"{ds_id}_2k.log")
            
            total_records = 0
            sample_msg = "Real-world historical telemetry"
            has_csv = os.path.exists(csv_file)

            if has_csv:
                try:
                    with open(csv_file, "r", encoding="utf-8", errors="ignore") as f:
                        reader = csv.DictReader(f)
                        rows = list(reader)
                        total_records = len(rows)
                        if rows:
                            sample_msg = rows[0].get("Content") or rows[0].get("message") or sample_msg
                except Exception:
                    pass
            elif os.path.exists(log_file):
                try:
                    with open(log_file, "r", encoding="utf-8", errors="ignore") as f:
                        lines = f.readlines()
                        total_records = len(lines)
                        if lines:
                            sample_msg = lines[0].strip()[:120]
                except Exception:
                    pass

            results.append(LogHubDatasetInfo(
                id=ds_id,
                name=meta["name"],
                category=meta["category"],
                description=meta["description"],
                total_raw_records=total_records,
                components=meta["components"],
                sample_message=sample_msg,
                has_structured_csv=has_csv
            ))

        return results

    def load_dataset_records(self, dataset_id: str) -> List[NormalizedTelemetryEvent]:
        """Loads and normalizes raw dataset records into internal schema."""
        ds_id = dataset_id.upper()
        ds_dir = os.path.join(self.base_path, ds_id)
        if not os.path.exists(ds_dir):
            # Try case-sensitive search
            for d in os.listdir(self.base_path):
                if d.lower() == dataset_id.lower():
                    ds_dir = os.path.join(self.base_path, d)
                    ds_id = d
                    break

        csv_file = os.path.join(ds_dir, f"{ds_id}_2k.log_structured.csv")
        events: List[NormalizedTelemetryEvent] = []

        if os.path.exists(csv_file):
            events = self._parse_structured_csv(ds_id, csv_file)
        else:
            log_file = os.path.join(ds_dir, f"{ds_id}_2k.log")
            if os.path.exists(log_file):
                events = self._parse_raw_log(ds_id, log_file)

        return events

    def _parse_structured_csv(self, ds_id: str, csv_path: str) -> List[NormalizedTelemetryEvent]:
        events: List[NormalizedTelemetryEvent] = []
        with open(csv_path, "r", encoding="utf-8", errors="ignore") as f:
            reader = csv.DictReader(f)
            for row in reader:
                msg = row.get("Content") or row.get("message") or ""
                raw_level = row.get("Level") or row.get("Type") or "INFO"
                sev = parse_severity(raw_level)

                # Component / Service mapping
                raw_comp = row.get("Component") or row.get("Process") or row.get("Node") or ds_id.lower()
                # Normalize component name
                svc_name = raw_comp.split("$")[0].split("(")[0].strip()
                if not svc_name or svc_name.isdigit():
                    svc_name = f"{ds_id.lower()}-service"

                host = row.get("Node") or row.get("host") or row.get("ADDR")
                if host and host.startswith("req-"):
                    # OpenStack puts req-id in ADDR column
                    trace_id = host.split()[0]
                    host = None
                else:
                    trace_id = None

                event_id = row.get("EventId") or "LOGHUB_EVENT"
                template = row.get("EventTemplate")

                meta: Dict[str, Any] = {
                    "loghub_dataset": ds_id,
                    "event_template": template,
                    "line_id": row.get("LineId")
                }
                if row.get("Pid"):
                    meta["pid"] = row.get("Pid")

                # Parse or default timestamp
                now_iso = datetime.now(timezone.utc).isoformat()

                events.append(NormalizedTelemetryEvent(
                    timestamp=now_iso,
                    source=f"loghub-{ds_id.lower()}",
                    environment="loghub-historical",
                    service=svc_name,
                    type=TelemetryType.LOG,
                    severity=sev,
                    event_type=f"{ds_id}_{event_id}",
                    message=msg,
                    trace_id=trace_id,
                    host=host,
                    metrics={"error_rate": 1.0 if sev in [TelemetrySeverity.ERROR, TelemetrySeverity.CRITICAL] else 0.0},
                    metadata=meta
                ))

        return events

    def _parse_raw_log(self, ds_id: str, log_path: str) -> List[NormalizedTelemetryEvent]:
        events: List[NormalizedTelemetryEvent] = []
        with open(log_path, "r", encoding="utf-8", errors="ignore") as f:
            for idx, line in enumerate(f):
                line = line.strip()
                if not line:
                    continue

                sev = TelemetrySeverity.INFO
                if "ERROR" in line or "error" in line or "failed" in line.lower():
                    sev = TelemetrySeverity.ERROR
                elif "WARN" in line or "warning" in line.lower():
                    sev = TelemetrySeverity.WARNING

                events.append(NormalizedTelemetryEvent(
                    timestamp=datetime.now(timezone.utc).isoformat(),
                    source=f"loghub-{ds_id.lower()}",
                    environment="loghub-historical",
                    service=f"{ds_id.lower()}-service",
                    type=TelemetryType.LOG,
                    severity=sev,
                    event_type=f"{ds_id}_RAW_LOG",
                    message=line,
                    metadata={"line_id": idx + 1, "loghub_dataset": ds_id}
                ))

        return events


